import subprocess
import numpy as np
import os

class StructureGenerator:
    def __init__(self, work_dir: str, spparks_exe: str = "spk_linux"):
        self.work_dir = work_dir
        self.exe = spparks_exe
        os.makedirs(work_dir, exist_ok=True)

    def generate_initial_microstructure(self, size: int, num_seeds: int, target_porosity: float) -> str:
        """
        Generates initial microstructure following the thesis recommendations.
        """

        # Phase 1: Create Input Script for Grain Growth
        growth_script_path = os.path.join(self.work_dir, "growth.in")
        dump_file = "dump_growth.txt"

        # Note: The syntax below is based on SPPARKS input script format
        growth_script = f"""
        seed 12345
        app_style potts
        dimension 3
        lattice sc/26n 1.0
        region box block 0 {size} 0 {size} 0 {size}
        create_box box
        create_sites box

        set site range 1 {size**3} value 0
        set site loop {num_seeds} unique value 1 {num_seeds}

        temperature 1.0
        stats 100

        run 100

        dump 1 all {dump_file}
        """

        with open(growth_script_path, "w") as f:
            f.write(growth_script)

        # Phase 2: Mock Execute SPPARKS
        # In real scenario: subprocess.run([self.exe, "-in", growth_script_path], ...)
        self._mock_spparks_execution(os.path.join(self.work_dir, dump_file), size, num_seeds)

        # Phase 3: Apply Porosity
        return self._apply_porosity(dump_file, target_porosity, size)

