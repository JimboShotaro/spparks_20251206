    def _apply_porosity(self, dump_file: str, porosity: float, size: int) -> str:
        # Mock reading
        data = np.random.randint(1, 20, size=(size, size, size))

        # Apply porosity
        total_sites = data.size
        num_pores = int(total_sites * porosity)

        indices = np.random.choice(total_sites, num_pores, replace=False)
        flat_data = data.flatten()
        flat_data[indices] = 0
        final_grid = flat_data.reshape((size, size, size))

        output_file = os.path.join(self.work_dir, "start_structure.txt")
        self._write_spparks_input_format(final_grid, output_file)

        return output_file

    def _parse_dump(self, filename, size):
        return np.zeros((size, size, size), dtype=int)

    def _write_spparks_input_format(self, grid, filename):
        flat = grid.flatten()
        with open(filename, "w") as f:
            f.write(f"# SPPARKS input file generated by NanoSinterWeb\n")
            f.write(f"{len(flat)} sites\n\n")
            f.write("Values\n\n")
            for i, val in enumerate(flat):
                f.write(f"{i+1} {val}\n")
